class ResearchPaper:
    """A generated research paper from discovery results."""

    def __init__(
        self,
        disease: str,
        discovery_type: str,
        hypotheses: list[dict[str, Any]],
        stats: dict[str, Any],
        external_factors: list[dict[str, Any]] = None,
    ):
        self.id = str(uuid4())
        self.disease = disease
        self.discovery_type = discovery_type
        self.hypotheses = hypotheses
        self.stats = stats
        self.external_factors = external_factors or []
        self.created_at = datetime.utcnow()
        self.sections: dict[str, str] = {}
        self.references: list[dict[str, str]] = []
        self.tables: list[dict[str, Any]] = []
        self.figures: list[dict[str, Any]] = []
        self.toc: list[dict[str, Any]] = []
        self.plotly_figures: list[dict[str, Any]] = []
        self.generation_time_seconds: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "disease": self.disease,
            "discovery_type": self.discovery_type,
            "created_at": self.created_at.isoformat(),
            "toc": self.toc,
            "sections": self.sections,
            "references": self.references,
            "tables": self.tables,
            "figures": self.figures,
            "plotly_figures": self.plotly_figures,
            "metadata": {
                "total_hypotheses": len(self.hypotheses),
                "total_agents": self.stats.get("total_agents", 0),
                "runtime_seconds": self.stats.get("runtime_seconds", 0),
                "best_confidence": self.stats.get("current_best_confidence", 0),
                "models_used": self.stats.get("models_active", []),
                "external_factors_count": len(self.external_factors),
                "generation_time_seconds": self.generation_time_seconds,
            },
        }


class CitationValidator:
    """Validates citations against PubMed to prevent hallucinated DOIs."""

    def __init__(self):
        self._validated_cache: dict[str, dict] = {}

    async def search_pubmed(self, query: str, max_results: int = 3) -> list[dict[str, str]]:
        """Search PubMed for real citations matching a query."""
        try:
            import aiohttp
            base_url = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils"
            email = settings.PUBMED_EMAIL

            # Search for PMIDs
            search_url = f"{base_url}/esearch.fcgi"
            params = {
                "db": "pubmed",
                "term": query,
                "retmax": max_results,
                "retmode": "json",
                "email": email,
            }

            async with aiohttp.ClientSession() as session:
                async with session.get(search_url, params=params, timeout=aiohttp.ClientTimeout(total=10)) as resp:
                    if resp.status != 200:
                        return []
                    data = await resp.json()
                    pmids = data.get("esearchresult", {}).get("idlist", [])

                if not pmids:
                    return []

                # Fetch citation details
                fetch_url = f"{base_url}/esummary.fcgi"
                fetch_params = {
                    "db": "pubmed",
                    "id": ",".join(pmids),
                    "retmode": "json",
                    "email": email,
                }

                async with session.get(fetch_url, params=fetch_params, timeout=aiohttp.ClientTimeout(total=10)) as resp:
                    if resp.status != 200:
                        return []
                    summary = await resp.json()

                citations = []
                results = summary.get("result", {})
                for pmid in pmids:
                    article = results.get(pmid, {})
                    if not article or pmid == "uids":
                        continue

                    authors_list = article.get("authors", [])
                    first_author = authors_list[0]["name"] if authors_list else "Unknown"
                    et_al = " et al." if len(authors_list) > 1 else ""

                    year = article.get("pubdate", "")[:4]
                    title = article.get("title", "")
                    journal = article.get("fulljournalname", article.get("source", ""))
                    doi_ids = [eid for eid in article.get("articleids", []) if eid.get("idtype") == "doi"]
                    doi = doi_ids[0]["value"] if doi_ids else ""

                    citation = {
                        "pmid": pmid,
                        "text": f"{first_author}{et_al} ({year}). {title} {journal}.",
                        "doi": f"https://doi.org/{doi}" if doi else "",
                        "title": title,
                        "year": year,
                        "journal": journal,
                        "verified": True,
                    }
                    citations.append(citation)
                    self._validated_cache[pmid] = citation

                return citations

        except Exception as e:
            logger.warning(f"PubMed search failed for '{query}': {e}")
            return []

    async def validate_and_collect_citations(
        self, disease: str, hypotheses: list[dict[str, Any]], external_factors: list[dict[str, Any]],
    ) -> list[dict[str, str]]:
        """Collect real, validated citations for the paper across multiple topics."""
        all_citations = []
        seen_pmids = set()

        # Build search queries from paper content
        queries = [
            f"{disease} treatment therapy",
            f"{disease} pathophysiology mechanisms",
            f"{disease} clinical trials 2024 2025",
            f"multi-model AI drug discovery",
            f"large language models biomedical research",
        ]

        # Add hypothesis-specific queries
        for h in hypotheses[:10]:
            title = h.get("title", "")
            if title:
                queries.append(f"{disease} {title[:60]}")

        # Add external factor queries
        factor_names = [f.get("name", "") for f in external_factors[:5] if f.get("name")]
        for name in factor_names:
            queries.append(f"{name} {disease} therapeutic effect")

        # Run PubMed searches in parallel batches
        tasks = [self.search_pubmed(q, max_results=2) for q in queries]
        results = await asyncio.gather(*tasks, return_exceptions=True)

        ref_id = 1
        for result in results:
            if isinstance(result, Exception):
                continue
            for citation in result:
                pmid = citation.get("pmid", "")
                if pmid and pmid not in seen_pmids:
                    seen_pmids.add(pmid)
                    citation["id"] = str(ref_id)
                    all_citations.append(citation)
                    ref_id += 1

        logger.info(f"Validated {len(all_citations)} real citations from PubMed")
        return all_citations


class PaperGenerationService:
    """
    Generates fully AI-driven research papers using all 4 models in parallel.
    No template fallbacks — every section is LLM-generated.
    """

    def __init__(self):
        self._llm = None
        self._citation_validator = CitationValidator()

    async def _get_llm(self):
        if self._llm is None:
            try:
                from app.agents.discovery_orchestrator import MultiModelLLM, TokenPool
                pool = TokenPool()
                self._llm = MultiModelLLM(pool)
                await self._llm.initialize()
            except Exception as e:
                logger.error(f"LLM initialization failed for paper generation: {e}")
                raise RuntimeError(f"LLM required for paper generation but unavailable: {e}")
        return self._llm

    async def generate_paper(
        self,
        disease: str,
        discovery_type: str,
        hypotheses: list[dict[str, Any]],
        stats: dict[str, Any],
        external_factors: list[dict[str, Any]] = None,
    ) -> ResearchPaper:
        """Generate a full research paper. Fails if exceeds 30-minute timeout."""
        start_time = time.time()

        paper = ResearchPaper(
            disease=disease,
            discovery_type=discovery_type,
            hypotheses=hypotheses,
            stats=stats,
            external_factors=external_factors,
        )

        try:
            await asyncio.wait_for(
                self._generate_all_sections(paper),
                timeout=PAPER_GENERATION_TIMEOUT_SECONDS,
            )
        except asyncio.TimeoutError:
            elapsed = time.time() - start_time
            raise RuntimeError(
                f"Paper generation exceeded 30-minute timeout ({elapsed:.0f}s elapsed). "
                f"Completed sections: {list(paper.sections.keys())}"
            )

        paper.generation_time_seconds = time.time() - start_time
        logger.info(
            f"Generated research paper '{paper.sections.get('title', 'Untitled')}' "
            f"in {paper.generation_time_seconds:.1f}s with {len(paper.tables)} tables, "
            f"{len(paper.plotly_figures)} Plotly figures, {len(paper.references)} verified references"
        )
        return paper

    async def _generate_all_sections(self, paper: ResearchPaper) -> None:
        """Generate all paper content using multiple models in parallel."""
        llm = await self._get_llm()
        from app.agents.discovery_orchestrator import ModelType

        # Build rich hypothesis context for all models
        hyp_context = self._build_hypothesis_context(paper)
        substance_context = self._build_substance_context(paper)

        # Phase 1: Parallel generation of independent sections across all 4 models
        phase1_tasks = {
            "title": self._generate_title_ai(llm, paper),
            "abstract": self._generate_abstract_ai(llm, paper, hyp_context),
            "introduction": self._generate_introduction_ai(llm, paper, hyp_context),
            "disease_background": self._generate_disease_background_ai(llm, paper),
            "methods": self._generate_methods_ai(llm, paper),
            "citations": self._citation_validator.validate_and_collect_citations(
                paper.disease, paper.hypotheses, paper.external_factors,
            ),
        }

        phase1_results = await asyncio.gather(
            *[asyncio.create_task(coro) for coro in phase1_tasks.values()],
            return_exceptions=True,
        )

        for (key, _), result in zip(phase1_tasks.items(), phase1_results):
            if isinstance(result, Exception):
                logger.error(f"Phase 1 section '{key}' failed: {result}")
                raise RuntimeError(f"Paper generation failed: section '{key}' error: {result}")
            if key == "citations":
                paper.references = result
            else:
                paper.sections[key] = result

        # Phase 2: Sections that depend on phase 1 content (use full context)
        phase2_tasks = {
            "results_overview": self._generate_results_overview_ai(llm, paper, hyp_context),
            "hypothesis_analyses": self._generate_hypothesis_deep_analyses(llm, paper),
            "external_factors_analysis": self._generate_external_factors_ai(llm, paper, substance_context),
            "molecular_mechanisms": self._generate_molecular_mechanisms_ai(llm, paper, hyp_context),
        }

        phase2_results = await asyncio.gather(
            *[asyncio.create_task(coro) for coro in phase2_tasks.values()],
            return_exceptions=True,
        )

        for (key, _), result in zip(phase2_tasks.items(), phase2_results):
            if isinstance(result, Exception):
                logger.error(f"Phase 2 section '{key}' failed: {result}")
                raise RuntimeError(f"Paper generation failed: section '{key}' error: {result}")
            paper.sections[key] = result

        # Phase 3: Discussion, Conclusion, and figures (depend on results)
        phase3_tasks = {
            "discussion": self._generate_discussion_ai(llm, paper, hyp_context),
            "limitations_future": self._generate_limitations_future_ai(llm, paper),
            "conclusion": self._generate_conclusion_ai(llm, paper, hyp_context),
            "plotly_figures": self._generate_plotly_figures(paper),
            "tables": self._generate_tables(paper),
        }

        phase3_results = await asyncio.gather(
            *[asyncio.create_task(coro) for coro in phase3_tasks.values()],
            return_exceptions=True,
        )

        for (key, _), result in zip(phase3_tasks.items(), phase3_results):
            if isinstance(result, Exception):
                logger.error(f"Phase 3 section '{key}' failed: {result}")
                raise RuntimeError(f"Paper generation failed: section '{key}' error: {result}")
            if key == "plotly_figures":
                paper.plotly_figures = result
            elif key == "tables":
                paper.tables = result
            else:
                paper.sections[key] = result

        # Build dynamic TOC from generated sections
        paper.toc = self._build_dynamic_toc(paper)

    def _build_hypothesis_context(self, paper: ResearchPaper) -> str:
        """Build a rich context string from all hypotheses for LLM prompts."""
        lines = []
        for i, h in enumerate(paper.hypotheses[:20], 1):
            conf = h.get("confidence", 0)
            lines.append(
                f"Hypothesis {i}: {h.get('title', 'Untitled')}\n"
                f"  Confidence: {conf:.1%} | Model: {h.get('model_used', 'unknown')}\n"
                f"  Mechanism: {h.get('mechanism', 'Not specified')}\n"
                f"  Description: {h.get('description', 'N/A')}\n"
                f"  Validated: {'Yes' if h.get('validated') else 'No'}"
            )
        return "\n\n".join(lines)

    def _build_substance_context(self, paper: ResearchPaper) -> str:
        """Build context from external factors/substances."""
        if not paper.external_factors:
            return "No external factors specified."

        by_category: dict[str, list] = {}
        for f in paper.external_factors:
            cat = f.get("category", "other")
            by_category.setdefault(cat, []).append(f)

        lines = []
        for cat, factors in by_category.items():
            names = [f.get("name", "Unknown") for f in factors]
            lines.append(f"{cat.title()}: {', '.join(names)}")

        return "\n".join(lines)

