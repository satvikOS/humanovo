    def _build_dynamic_toc(self, paper: ResearchPaper) -> list[dict[str, Any]]:
        """Build a fully dynamic TOC from generated sections."""
        toc = []
        section_order = [
            ("title", "Title Page", 0),
            ("abstract", "Abstract", 0),
            ("introduction", "Introduction", 0),
            ("disease_background", "Disease Background", 1),
            ("methods", "Methods", 0),
            ("results_overview", "Results Overview", 0),
            ("hypothesis_analyses", "Detailed Hypothesis Analyses", 1),
            ("molecular_mechanisms", "Molecular Mechanisms", 1),
            ("external_factors_analysis", "External Factors Analysis", 0),
            ("discussion", "Discussion", 0),
            ("limitations_future", "Limitations and Future Directions", 1),
            ("conclusion", "Conclusion", 0),
        ]

        idx = 1
        for section_key, display_name, depth in section_order:
            if section_key in paper.sections and paper.sections[section_key]:
                toc.append({
                    "id": f"section-{section_key}",
                    "label": display_name,
                    "section_key": section_key,
                    "depth": depth,
                    "index": idx,
                })
                idx += 1

        # Add tables and figures to TOC
        if paper.tables:
            toc.append({"id": "section-tables", "label": "Tables", "section_key": "tables", "depth": 0, "index": idx})
            idx += 1
        if paper.plotly_figures:
            toc.append({"id": "section-figures", "label": "Figures", "section_key": "figures", "depth": 0, "index": idx})
            idx += 1
        if paper.references:
            toc.append({"id": "section-references", "label": "References", "section_key": "references", "depth": 0, "index": idx})

        return toc

